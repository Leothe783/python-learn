# My Daily Routine Printer
# This program prints a title, daily routine steps, and calculates weekly study time.

# 1. Print the title
print("=== MY DAILY ROUTINE ===")

# 2. Print routine steps using the print() function
print("1. Waking up early in the morning")
print("2. Getting ready and going to school")
print("3. Attending classes and learning new things")
print("4. Playing sports and having fun")
print("5. Studying and doing homework in the evening")

# 3. Calculate and print total study time in a week (e.g., 2 hours per day for 5 days)
hours_per_day = 2
days_in_week = 5
total_study_time = hours_per_day * days_in_week

print("\n--- Weekly Study Summary ---")
print("Hours spent studying per day:", hours_per_day)
print("Total study time in a week (hours):", total_study_time)